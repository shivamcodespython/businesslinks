// Helper to bridge offerings to products for backwards-compat
function makeCompatibleOfferings(offerings: UniversalOffering[]): { offerings: UniversalOffering[]; products: ProductItem[]; services: UniversalOffering[] } {
  const products: ProductItem[] = offerings
    .filter(o => o.type === 'product')
    .map(o => ({
      ...o,
      unitPrice: o.price,
    }));
  const services = offerings.filter(o => o.type === 'service');
  return { offerings, products, services };
}

